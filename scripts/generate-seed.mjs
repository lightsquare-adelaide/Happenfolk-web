// Regenerate the checked-in SQL from the shared local/remote sample manifest.
import { writeFileSync } from "node:fs";
import { artists, sampleContent, SAMPLE_TAG } from "./fixtures/sample-data.mjs";
const quote = (value) => {
  if (value === null) return "null";
  if (Array.isArray(value)) return `array[${value.map(quote).join(",")}]::text[]`;
  if (typeof value !== "string") return String(value);
  return `'${value.replaceAll("'", "''")}'`;
};
const lines = ["-- Generated by node scripts/generate-seed.mjs. Synthetic sample data only.",
  "-- Local-only accounts: sample.artist.NN@example.test; password Sample-Happenfolk-2026!",
  "-- Upload generated placeholders after reset with npm run seed:media.", "begin;"];
function insert(table, rows) {
  if (!rows.length) return;
  const columns = Object.keys(rows[0]);
  lines.push(`insert into ${table} (${columns.join(",")}) values\n${rows.map((r) => `(${columns.map((c) => quote(r[c])).join(",")})`).join(",\n")} on conflict do nothing;`);
}
